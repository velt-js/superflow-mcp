// Builds src/playbooks/generated.ts from skills/<name>/SKILL.md (`pnpm playbooks`).
//
// One source, three outputs: the superflow_use_playbook tool returns these bodies, the MCP
// prompts of the same names serve them, and the server instructions list them. The package
// ships only dist/, so the text is inlined here rather than read from disk at run time.
// `--check` fails when the committed file is out of date (CI runs it).
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const SKILLS = join(ROOT, "skills");
const OUT = join(ROOT, "src", "playbooks", "generated.ts");
const NAME = /^[a-z][a-z0-9_]*$/;

function parse(file, folder) {
  const raw = readFileSync(file, "utf8").replace(/\r\n/g, "\n");
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(raw);
  if (!match) throw new Error(`${file}: missing the --- frontmatter --- block.`);
  const meta = {};
  for (const line of match[1].split("\n")) {
    if (!line.trim()) continue;
    const pair = /^([a-z_]+):\s*(.*)$/.exec(line);
    if (!pair) throw new Error(`${file}: cannot read frontmatter line "${line}".`);
    meta[pair[1]] = pair[2].trim();
  }
  for (const key of ["name", "title", "description", "when", "clients"]) {
    if (!meta[key]) throw new Error(`${file}: frontmatter needs "${key}".`);
  }
  if (meta.name !== folder) throw new Error(`${file}: name "${meta.name}" must match its folder "${folder}".`);
  if (!NAME.test(meta.name)) throw new Error(`${file}: name "${meta.name}" must be lowercase letters, digits and underscores.`);
  const body = match[2].trim();
  return { name: meta.name, title: meta.title, description: meta.description, when: meta.when, clients: meta.clients, body };
}

function build() {
  const folders = readdirSync(SKILLS, { withFileTypes: true }).filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort();
  const playbooks = folders.map((folder) => {
    const file = join(SKILLS, folder, "SKILL.md");
    if (!existsSync(file)) throw new Error(`skills/${folder} has no SKILL.md.`);
    return parse(file, folder);
  });
  return [
    "// Generated by scripts/build-playbooks.mjs from skills/*/SKILL.md. Do not edit: run `pnpm playbooks`.",
    "",
    "export interface Playbook {",
    "  name: string;",
    "  title: string;",
    "  description: string;",
    "  /** When to call it, as the end of \"when the user wants to ...\". */",
    "  when: string;",
    "  clients: string;",
    "  body: string;",
    "}",
    "",
    `export const PLAYBOOKS: readonly Playbook[] = ${JSON.stringify(playbooks, null, 2)};`,
    "",
  ].join("\n");
}

const next = build();
if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== next) {
    console.error("playbooks: src/playbooks/generated.ts is out of date. Run `pnpm playbooks` and commit it.");
    process.exit(1);
  }
  console.log("playbooks: src/playbooks/generated.ts is current.");
} else {
  writeFileSync(OUT, next);
  console.log(`Wrote src/playbooks/generated.ts (${(next.match(/"name":/g) ?? []).length} playbooks).`);
}
